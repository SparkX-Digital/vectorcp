"""Bounded DNS record snapshots and a durable publication recovery marker."""
import hashlib
import json
import os
import re
import secrets
import shutil
import stat
import time

from .core import DOMAIN, Fault, integer

MAX_SNAPSHOT = 256 * 1024
SNAPSHOTS_PER_SITE = 5
SNAPSHOTS_GLOBAL = 512


def migrate(db):
    db.executescript('''
      CREATE TABLE IF NOT EXISTS dns_snapshots (
        id TEXT PRIMARY KEY, site_id INTEGER NOT NULL REFERENCES sites(id),
        created INTEGER NOT NULL, serial INTEGER NOT NULL, records INTEGER NOT NULL,
        reason TEXT NOT NULL, payload TEXT NOT NULL, sha256 TEXT NOT NULL);
      CREATE INDEX IF NOT EXISTS dns_snapshot_site ON dns_snapshots(site_id,created);
      CREATE TABLE IF NOT EXISTS dns_tombstones (
        site_id INTEGER PRIMARY KEY REFERENCES sites(id), serial INTEGER NOT NULL,
        updated INTEGER NOT NULL);
    ''')


def encode(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=True, separators=(',', ':')) + '\n'


def parse(payload, domain):
    from .dns import validate, validate_record_name
    if not isinstance(payload, str) or len(payload.encode()) > MAX_SNAPSHOT:
        raise Fault('Choose a DNS snapshot JSON file up to 256 KB.')
    try:
        value = json.loads(payload)
    except (ValueError, RecursionError):
        raise Fault('This DNS snapshot is not valid JSON.')
    if not isinstance(value, dict) or value.get('format') != 'vectorcp-dns-records' or type(value.get('version')) is not int or value['version'] != 1:
        raise Fault('Use a VectorCP DNS records snapshot.')
    if value.get('domain') != domain:
        raise Fault('The snapshot domain must exactly match this website.', 409)
    serial = integer(value.get('source_serial'), 'snapshot serial', 0, 4294967295)
    created = integer(value.get('created'), 'snapshot date', 0, 4294967295)
    records = value.get('records')
    if not isinstance(records, list) or len(records) > 100:
        raise Fault('A DNS snapshot supports up to 100 records.')
    normalized, names, unique = [], {}, set()
    for raw in records:
        if not isinstance(raw, dict):
            raise Fault('Every snapshot record must be an object.')
        record = validate(raw)
        validate_record_name(record['name'],domain)
        if record['name'] == '_vectorcp':
            raise Fault('Ownership records are generated by VectorCP, not restored from snapshots.')
        key = (record['name'], record['type'], record['value'])
        if key in unique:
            raise Fault('The DNS snapshot contains duplicate records.')
        previous = names.setdefault(record['name'], set())
        if previous and ('CNAME' in previous or record['type'] == 'CNAME'):
            raise Fault('A CNAME must be the only record at its name.')
        previous.add(record['type'])
        unique.add(key)
        normalized.append(record)
    return {'serial': serial, 'created': created, 'records': normalized}


class DNSRecovery:
    def __init__(self, dns):
        self.dns, self.e = dns, dns.e
        self.pending = self.e.state / 'dns-pending.json'

    def sync_parent(self):
        descriptor = os.open(self.e.state, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(descriptor)
        finally:
            os.close(descriptor)

    def begin(self, site, serial):
        if self.pending.exists() or self.pending.is_symlink():
            raise Fault('A DNS change requires recovery before another change can start.', 503)
        value = encode({'version': 1, 'site_id': site['id'], 'domain': site['domain'], 'serial': serial})
        temporary = self.e.state / ('.dns-pending-' + secrets.token_hex(12))
        try:
            with temporary.open('x', encoding='utf8') as stream:
                os.chmod(temporary, 0o600)
                stream.write(value)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, self.pending)
            self.sync_parent()
        finally:
            temporary.unlink(missing_ok=True)

    def marker(self):
        try:
            descriptor = os.open(self.pending, os.O_RDONLY | os.O_NOFOLLOW)
            with os.fdopen(descriptor, encoding='utf8') as stream:
                info = os.fstat(stream.fileno())
                if not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid() or info.st_mode & 0o077 or info.st_size > 4096:
                    raise ValueError()
                value = json.load(stream)
            if not isinstance(value, dict) or value.get('version') != 1:
                raise ValueError()
            integer(value.get('site_id'), 'recovery website', 1, 2147483647)
            integer(value.get('serial'), 'recovery serial', 0, 4294967295)
            if not isinstance(value.get('domain'), str) or not DOMAIN.fullmatch(value['domain']):
                raise ValueError()
            return value
        except (OSError, ValueError, RecursionError, Fault):
            raise Fault('The private DNS recovery marker needs server-owner inspection.', 503)

    def clear(self):
        marker = self.marker()
        # A killed writer can leave a temporary file before its atomic rename.
        for directory, pattern in ((self.dns.zones,r'\.site-[1-9][0-9]*\.zone\.new-[0-9a-f]{24}'),
                                   (self.dns.config,r'\.zones\.conf\.new-[0-9a-f]{24}')):
            for path in directory.glob('.*.new-*'):
                info = path.lstat()
                if re.fullmatch(pattern,path.name) and stat.S_ISREG(info.st_mode) and info.st_uid == os.geteuid():
                    path.unlink()
            if directory.exists():
                self.dns.sync_directory(directory)
        self.pending.unlink()
        self.sync_parent()

    def quarantine(self, files):
        if not files:
            return None
        root = self.e.state / 'dns-quarantine'
        root.mkdir(mode=0o700, exist_ok=True)
        if root.is_symlink():
            raise Fault('Inspect the private DNS quarantine directory before repairing DNS.', 503)
        existing = list(root.iterdir())
        # Repeated startup recovery must not fill the quota with identical
        # copies when an unrelated service failure persists.
        names = {p.name for p in files}
        for directory in existing[:8]:
            if directory.is_symlink() or not directory.is_dir():
                continue
            saved = list(directory.iterdir())
            if len(saved) != len(files) or {p.name for p in saved} != names:
                continue
            if all(not p.is_symlink() and p.is_file() and p.stat().st_size <= 256*1024 for p in saved):
                if all((directory/p.name).read_bytes() == p.read_bytes() for p in files):
                    return directory.name
        if len(existing) >= 8:
            raise Fault('DNS quarantine is full. The server owner must archive older recovery directories first.', 409)
        required = sum(p.stat().st_size for p in files)
        retained = sum(p.stat().st_size for p in root.rglob('*') if p.is_file())
        if required + retained > 128 * 1024 ** 2:
            raise Fault('DNS quarantine has reached its 128 MB limit. Archive older recovery directories first.',409)
        if shutil.disk_usage(root).free < required + 64 * 1024 ** 2:
            raise Fault('DNS repair needs enough space for quarantined files plus 64 MB.', 409)
        destination = root / (str(int(time.time())) + '-' + secrets.token_hex(8))
        destination.mkdir(mode=0o700)
        for path in files:
            target = destination / path.name
            with path.open('rb') as source, target.open('xb') as output:
                os.chmod(target, 0o600)
                shutil.copyfileobj(source, output)
                output.flush()
                os.fsync(output.fileno())
        self.dns.sync_directory(destination)
        self.dns.sync_directory(root)
        return destination.name

    def recover(self, db):
        """Rebuild from the last committed database; never trust marker payloads as records."""
        marker = self.marker()
        site = db.execute('SELECT * FROM sites WHERE id=?', (marker['site_id'],)).fetchone()
        if not site or site['domain'] != marker['domain']:
            raise Fault('The DNS recovery website changed. Server-owner inspection is required.', 503)
        zone = db.execute('SELECT * FROM dns_zones WHERE site_id=?', (site['id'],)).fetchone()
        if zone:
            current, proposed = zone['serial'], marker['serial']
            # RFC 1982 ordering, including wrap: recovery must not republish an older SOA.
            latest = proposed if (proposed - current) % 4294967296 < 2147483648 else current
            db.execute('UPDATE dns_zones SET serial=? WHERE site_id=?', ((latest + 1) % 4294967296, site['id']))
            db.commit()
        self.dns.repair_all(db, protected_serial=site['id'] if zone else None)
        db.commit()
        self.clear()

    def list(self, db, site):
        return [dict(row) for row in db.execute('''SELECT id,created,serial,records,reason,sha256
            FROM dns_snapshots WHERE site_id=? ORDER BY created DESC,id DESC''', (site['id'],))]

    def snapshot(self, db, site, zone, reason='manual', payload=None):
        from .dns import validate
        if payload is None:
            if not zone:
                raise Fault('Create a DNS zone before saving a snapshot.', 409)
            records = []
            for row in db.execute('SELECT name,type,ttl,value FROM dns_records WHERE site_id=? ORDER BY name,type,id', (site['id'],)):
                record = dict(row)
                if record['type'] == 'TXT':
                    record['value'] = json.loads(record['value'])
                elif record['type'] == 'CAA':
                    flag, tag, value = record['value'].split(None, 2)
                    record['value'] = flag + ' ' + tag + ' ' + json.loads(value)
                # Refuse corrupt stored records rather than exporting a misleading copy.
                validate(record)
                records.append(record)
            payload = encode({'format': 'vectorcp-dns-records', 'version': 1,
                'domain': site['domain'], 'source_serial': zone['serial'],
                'created': int(time.time()), 'records': records})
        parsed = parse(payload, site['domain'])
        if (db.execute('SELECT COUNT(*) FROM dns_snapshots WHERE site_id=?', (site['id'],)).fetchone()[0] >= SNAPSHOTS_PER_SITE
                or db.execute('SELECT COUNT(*) FROM dns_snapshots').fetchone()[0] >= SNAPSHOTS_GLOBAL):
            raise Fault('DNS snapshot storage is full. Download and remove an older snapshot first.', 409)
        ident = secrets.token_hex(12)
        sha = hashlib.sha256(payload.encode()).hexdigest()
        db.execute('INSERT INTO dns_snapshots VALUES(?,?,?,?,?,?,?,?)', (ident, site['id'], int(time.time()),
            parsed['serial'], len(parsed['records']), reason, payload, sha))
        return {'id': ident, 'sha256': sha, 'records': len(parsed['records'])}

    def get(self, db, site, ident):
        if not isinstance(ident, str) or not re.fullmatch(r'[0-9a-f]{24}', ident):
            raise Fault('Invalid DNS snapshot.')
        row = db.execute('SELECT * FROM dns_snapshots WHERE id=? AND site_id=?', (ident, site['id'])).fetchone()
        if not row:
            raise Fault('DNS snapshot not found.', 404)
        if hashlib.sha256(row['payload'].encode()).hexdigest() != row['sha256']:
            raise Fault('The DNS snapshot integrity check failed.', 409)
        return row
